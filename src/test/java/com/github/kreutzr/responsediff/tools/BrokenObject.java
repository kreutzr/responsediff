package com.github.kreutzr.responsediff.tools;

/**
 * Testobject to cover catch clauses in tests.
 */
public class BrokenObject
{
  public static final String ERROR_MESSAGE = "Object is broken by design.";

  /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  private BrokenObject parent_ = null;
  private String       value_  = null;

  /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  public void setParent( final BrokenObject parent )
  {
	  parent_ = parent;
  }

  /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  public BrokenObject getParent()
  {
	  return parent_;
  }


  /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  public void setValue ( final String value )
  {
	  value_ = value;
  }

  /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  public String getValue()
  {
	  return value_;
  }

  /////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

  @Override
  public String toString()
  {
    throw new RuntimeException( ERROR_MESSAGE );
  }
}
